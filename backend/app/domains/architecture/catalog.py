RELATIONSHIP_KIND_BY_TYPE = {
    "contains": "hierarchy",
    "deployed_in": "hierarchy",
    "connects_to": "network_data_flow",
    "depends_on": "service_dependency",
    "integrated_with": "association",
}


def classify_relationship_rule(source_type: str, target_type: str, relationship_type: str) -> dict:
    """Return an Azure-aware result without using node geometry or names."""
    kind = RELATIONSHIP_KIND_BY_TYPE.get(relationship_type)
    if relationship_type not in VALID_RELATIONSHIP_TYPES:
        return {"valid": False, "status": "INVALID", "reason": "Unsupported relationship type", "kind": kind}
    if source_type == target_type and relationship_type == "contains":
        return {"valid": False, "status": "INVALID", "reason": "A resource cannot contain itself", "kind": kind}
    if source_type == "user" and relationship_type in {"depends_on", "deployed_in", "contains"}:
        return {"valid": False, "status": "INVALID", "reason": "User resources can only use connects_to relationships", "kind": kind}

    allowed = VALID_RELATIONSHIP_MATRIX.get((source_type, target_type))
    if allowed and relationship_type in allowed:
        return {"valid": True, "status": "VALID", "reason": None, "kind": kind}
    conditional = CONDITIONAL_RELATIONSHIP_MATRIX.get((source_type, target_type))
    if conditional and relationship_type in conditional:
        return {
            "valid": True,
            "status": "CONDITIONAL",
            "reason": "Supported, but requires additional Azure configuration such as networking or DNS",
            "kind": kind,
        }
    # Preserve the existing escape hatch for a logical connection that Azure
    # knowledge does not model yet, but make the uncertainty explicit.
    if allowed is None and relationship_type == "connects_to":
        return {"valid": True, "status": "UNKNOWN", "reason": "Capability metadata is incomplete for this resource pair", "kind": kind}
    if source_type not in AZURE_CAPABILITY_MODEL or target_type not in AZURE_CAPABILITY_MODEL:
        return {"valid": True, "status": "UNKNOWN", "reason": "Capability metadata is incomplete for this resource pair", "kind": kind}
    return {"valid": False, "status": "INVALID", "reason": "Relationship type is not valid for this resource pair", "kind": kind}
